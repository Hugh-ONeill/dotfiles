-- ═══════════════════════════════════════════════════════════════════════════
-- Workspace assignments
-- ═══════════════════════════════════════════════════════════════════════════
-- environment/workspaces.lua is GENERATED by scripts/handle-monitors.sh from
-- the connected monitors (single: all on the primary; dual: odd/even split)
-- and rewritten on hotplug, followed by a reload. Edit the script, not the file.

-- pcall: a missing file (fresh checkout before the script has run) must not
-- take the whole config down with it.
local ok, assignments = pcall(require, "environment.workspaces")
for _, ws in ipairs(ok and assignments or {}) do
    hl.workspace_rule(ws)
end
