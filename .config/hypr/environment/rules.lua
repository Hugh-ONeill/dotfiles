-- File dialogs
for _, title in ipairs({ "^(Open File).*", "^(Save As).*", "^(Select a File).*", "^(Choose Files).*", "^(Confirm to replace files).*" }) do
    rule("float:" .. title, { title = title }, { float = true })
end
rule("size:open-file", { title = "^(Open File).*" }, { size = "800 600" })
rule("size:save-as",   { title = "^(Save As).*" },   { size = "800 600" })

-- System dialogs
