-- A rule's `match` table takes the same regexes the old `match:class ...`
-- did; effects are fields on the same table (see HL.WindowRuleSpec and the
-- effect list in /usr/share/hypr/stubs/hl.meta.lua). Names are optional, but
-- a rule re-declared under the SAME name extends that rule instead of making
-- a new one, so every name here is unique.

local function rule(name, match, effects)
    effects.name  = name
    effects.match = match
    hl.window_rule(effects)
end

local function float_classes(classes, extra)
    for _, class in ipairs(classes) do
        local effects = { float = true }
        for k, v in pairs(extra or {}) do
            effects[k] = v
        end
        rule("float:" .. class, { class = class }, effects)
    end
end

