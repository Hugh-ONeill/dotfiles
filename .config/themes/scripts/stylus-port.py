#!/usr/bin/env python3
"""Port Catppuccin userstyles to the theme system, automatically.

Upstream styles keep every color in one shared Less library, so a port is a
single substitution: the library import is replaced by the same library with
its palette maps pointing at template variables. The style body is untouched.
All four flavors resolve to the active theme, and @lightFlavor/@darkFlavor are
pinned to latte (light themes) or mocha (dark), so flavor conditionals follow
the theme too.

Ported templates land in templates/stylus/ and are tracked in upstream.json
with "auto": true; `sync` re-ports them whenever upstream changes.

Usage:
  stylus-port.py list [--ported]      upstream styles and their port status
  stylus-port.py add NAME... | --all  port styles (--replace takes over a hand port)
  stylus-port.py rm NAME...           drop auto-ported styles
  stylus-port.py sync [--notify]      pull upstream, re-port what changed
  stylus-port.py check NAME... | --all  convert + compile only, write nothing
"""

from __future__ import annotations

import argparse
import concurrent.futures
import json
import re
import shutil
import subprocess
import sys
import time
from dataclasses import dataclass, field
from pathlib import Path

THEMES_DIR = Path.home() / ".config" / "themes"
TEMPLATES = THEMES_DIR / "templates" / "stylus"
GENERATED = THEMES_DIR / "generated"
CURRENT = THEMES_DIR / "current"
PALETTES = THEMES_DIR / "palettes"
MANIFEST = THEMES_DIR / "upstream.json"
GENERATE = THEMES_DIR / "scripts" / "generate-theme.sh"
CLONE = Path.home() / ".cache" / "theme-sources" / "userstyles"
REPLACED = Path.home() / ".cache" / "themes" / "stylus-replaced"
REPO_URL = "https://github.com/catppuccin/userstyles.git"
LIB_URL = "https://userstyles.catppuccin.com/lib/"

# Catppuccin color name -> template variable (same mapping the hand ports use)
NAMES: dict[str, str] = {
    "rosewater": "ACCENT", "flamingo": "ACCENT_SECONDARY", "pink": "ACCENT",
    "mauve": "ACCENT", "red": "SEM_ERR", "maroon": "SEM_ERR",
    "peach": "SEM_WARN", "yellow": "SEM_WARN", "green": "SEM_OK",
    "teal": "ACCENT_TERTIARY", "sky": "SEM_INFO", "sapphire": "SEM_INFO",
    "blue": "SEM_LINK", "lavender": "ACCENT_BRIGHT",
    "text": "TEXT", "subtext1": "SUBTEXT1", "subtext0": "SUBTEXT0",
    "overlay2": "OVERLAY2", "overlay1": "OVERLAY1", "overlay0": "OVERLAY0",
    "surface2": "SURFACE2", "surface1": "SURFACE1", "surface0": "SURFACE0",
    "base": "BASE", "mantle": "MANTLE", "crust": "CRUST",
}
# Upstream's default accent; maps to ${ACCENT}
ACCENT_NAME = "mauve"

PRELUDE_HEAD = f"""\
// ============================================================
// THEME PALETTE
// ============================================================
// Generated by stylus-port.py: the Catppuccin lib with its palette pointed
// at the theme system. `theme stylus sync` rewrites this file; don't edit it.
@lightFlavor: ${{THEME_FLAVOR}};
@darkFlavor: ${{THEME_FLAVOR}};
@accentColor: {ACCENT_NAME};
"""


class PortError(Exception):
    pass


# ============================================================
# UPSTREAM CLONE
# ============================================================


def git(*args: str, check: bool = True) -> str:
    out = subprocess.run(
        ["git", "-C", str(CLONE), *args], capture_output=True, text=True, timeout=300
    )
    if check and out.returncode != 0:
        raise PortError(f"git {' '.join(args)}: {out.stderr.strip()}")
    return out.stdout.strip()


def ensure_clone(pull: bool) -> None:
    if not (CLONE / ".git").is_dir():
        CLONE.parent.mkdir(parents=True, exist_ok=True)
        out = subprocess.run(
            ["git", "clone", "--quiet", "--depth", "1", "--filter=blob:none",
             "--sparse", REPO_URL, str(CLONE)],
            capture_output=True, text=True, timeout=300,
        )
        if out.returncode != 0:
            raise PortError(f"git clone: {out.stderr.strip()}")
        git("sparse-checkout", "set", "styles", "lib")
    elif pull:
        git("pull", "--quiet", "--ff-only")


def head_sha() -> str:
    return git("rev-parse", "HEAD")[:12]


def upstream_names() -> list[str]:
    return sorted(
        p.parent.name for p in (CLONE / "styles").glob("*/catppuccin.user.less")
    )


def source_path(name: str) -> Path:
    return CLONE / "styles" / name / "catppuccin.user.less"


# ============================================================
# CONVERSION
# ============================================================

HEADER = re.compile(r"/\* ==UserStyle==\n(.*?)==/UserStyle== \*/", re.DOTALL)
LIB_IMPORT = re.compile(
    r'^[ \t]*@import\s+"' + re.escape(LIB_URL) + r'([^"]+)";[ \t]*\n', re.MULTILINE
)
OTHER_IMPORT = re.compile(r"@import\s[^;]*;")
MAP_BLOCK = re.compile(r"^@(catppuccin(?:-filters)?):\s*\{.*?^\};", re.DOTALL | re.MULTILINE)
MAP_ENTRY = re.compile(r"@([a-z0-9]+):\s*([^;{}]+);")
STD_VARS = re.compile(r"^@var select (lightFlavor|darkFlavor|accentColor) .*\n", re.MULTILINE)
HEX = re.compile(r"(?:#|%23)([0-9a-fA-F]{6})\b")


@dataclass
class Ported:
    name: str
    text: str
    warnings: list[str] = field(default_factory=list)


def lib_source(rel: str, seen: set[str]) -> str:
    """Upstream lib file with nested lib imports inlined."""
    if rel in seen:
        return ""
    seen.add(rel)
    path = CLONE / "lib" / rel
    if not path.is_file():
        raise PortError(f"lib/{rel} not in the upstream clone")
    return LIB_IMPORT.sub(lambda m: lib_source(m.group(1), seen), path.read_text())


def palette_hexes(lib: str) -> set[str]:
    """Every Catppuccin hex in the lib, to spot hardcoded ones in a style."""
    out: set[str] = set()
    for block in MAP_BLOCK.finditer(lib):
        if block.group(1) == "catppuccin":
            out.update(h.lower() for h in re.findall(r"#([0-9a-fA-F]{6})\b", block.group(0)))
    return out


def retarget_lib(lib: str) -> str:
    """Point the lib's palette and filter maps at template variables."""

    def block(m: re.Match[str]) -> str:
        suffix = "_FILTER" if m.group(1).endswith("filters") else ""

        def entry(e: re.Match[str]) -> str:
            var = NAMES.get(e.group(1))
            if var is None:
                raise PortError(f"lib has a color this port doesn't map: @{e.group(1)}")
            return f"@{e.group(1)}: ${{{var}{suffix}}};"

        return MAP_ENTRY.sub(entry, m.group(0))

    out, count = MAP_BLOCK.subn(block, lib)
    if count == 0:
        raise PortError("no @catppuccin palette map found in the upstream lib")
    return out


def port_header(header: str) -> str:
    header = STD_VARS.sub("", header)
    header = re.sub(r"^@updateURL .*\n", "", header, flags=re.MULTILINE)
    # Distinct from an installed upstream copy, like the hand ports
    header = re.sub(
        r"^(@name .*?)\s+Catppuccin[ \t]*$", r"\1 Custom", header, count=1, flags=re.MULTILINE
    )
    return header


def convert(name: str) -> Ported:
    src = source_path(name)
    if not src.is_file():
        raise PortError(f"no upstream style named {name!r}")
    text = src.read_text()
    m = HEADER.search(text)
    if m is None:
        raise PortError("no ==UserStyle== header")
    body = text[m.end():]
    warnings: list[str] = []

    seen: set[str] = set()
    hexes: set[str] = set()
    first = True

    def inline(im: re.Match[str]) -> str:
        nonlocal first
        raw = lib_source(im.group(1), seen)
        if not raw:
            return ""
        hexes.update(palette_hexes(raw))
        head = PRELUDE_HEAD if first else ""
        first = False
        return head + retarget_lib(raw).rstrip("\n") + "\n"

    body, count = LIB_IMPORT.subn(inline, body)
    if count == 0:
        raise PortError("style doesn't import the Catppuccin lib")

    style = body[body.rfind("#lib {"):] if "#lib {" in body else body
    for imp in OTHER_IMPORT.findall(style):
        flat = " ".join(imp.split())
        if "catppuccin" in flat and "variables" not in flat:
            warnings.append(f"remote Catppuccin CSS keeps its own colors: {flat[:110]}")
    hard = sorted({h.lower() for h in HEX.findall(style)} & hexes)
    if hard:
        warnings.append("hardcoded Catppuccin colors left as-is: " + " ".join("#" + h for h in hard))
    if re.search(r"\$\{?[A-Z][A-Z0-9_]*\}?", text):
        warnings.append("upstream text contains $VAR-like tokens; envsubst may touch them")

    out = f"/* ==UserStyle==\n{port_header(m.group(1))}==/UserStyle== */{body}"
    return Ported(name, out, warnings)


# ============================================================
# VALIDATION
# ============================================================

VAR_LINE = re.compile(r"^@var\s+(\w+)\s+([\w-]+)\s+\"[^\"]*\"\s+(.*)$", re.MULTILINE)
TMPL_VAR = re.compile(r"\$\{([A-Z0-9_]+)\}")


def var_default(kind: str, rest: str) -> str:
    """Less value Stylus would inject for a @var at its default."""
    rest = rest.strip()
    if kind == "select":
        opts = re.findall(r'"([^"]+)"', rest)
        chosen = next((o for o in opts if o.endswith("*")), opts[0] if opts else "none")
        return chosen.rstrip("*").split(":", 1)[0]
    if kind == "range":
        parts = [p.strip().strip("'\"") for p in rest.strip("[]").split(",")]
        unit = parts[4] if len(parts) > 4 else ""
        return parts[0] + unit
    if kind == "text":
        return rest
    return rest  # checkbox, number, color


def render_dummy(template: str, flavor: str) -> str:
    """Template with placeholder colors, plus Stylus-style @var definitions."""

    def sub(m: re.Match[str]) -> str:
        var = m.group(1)
        if var == "THEME_FLAVOR":
            return flavor
        if var.endswith("_FILTER"):
            return "invert(50%) sepia(10%)"
        return "#%06x" % (sum(var.encode()) * 7919 % 0xFFFFFF)

    body = TMPL_VAR.sub(sub, template)
    header = HEADER.search(template)
    defs = ""
    if header:
        for kind, var, rest in VAR_LINE.findall(header.group(1)):
            defs += f"@{var}: {var_default(kind, rest)};\n"
    return defs + body


def compile_less(source: str) -> str:
    """lessc error text, or '' when the source compiles."""
    out = subprocess.run(
        ["lessc", "--no-color", "-"], input=source, capture_output=True, text=True, timeout=120
    )
    if out.returncode == 0:
        return ""
    return (out.stderr.strip() or out.stdout.strip()).split("\n")[0][:200]


def validate(p: Ported) -> str:
    left = sorted(set(TMPL_VAR.findall(p.text)) - known_vars())
    if left:
        return "unknown template vars: " + " ".join(left)
    for flavor in ("mocha", "latte"):
        err = compile_less(render_dummy(p.text, flavor))
        if err:
            return f"lessc ({flavor}): {err}"
    return ""


def known_vars() -> set[str]:
    base = set(NAMES.values())
    return base | {v + "_FILTER" for v in base} | {"THEME_FLAVOR"}


def port_many(names: list[str]) -> tuple[list[Ported], dict[str, str]]:
    """Convert + compile-check in parallel; returns (good, {name: error})."""

    def one(name: str) -> tuple[str, Ported | None, str]:
        try:
            p = convert(name)
        except (PortError, OSError) as e:
            return name, None, str(e)
        err = validate(p) if shutil.which("lessc") else ""
        return name, (None if err else p), err

    good: list[Ported] = []
    bad: dict[str, str] = {}
    with concurrent.futures.ThreadPoolExecutor(max_workers=8) as pool:
        for name, p, err in pool.map(one, names):
            if p is None:
                bad[name] = err
            else:
                good.append(p)
    return good, bad


# ============================================================
# MANIFEST
# ============================================================


def load_manifest() -> dict:
    return json.loads(MANIFEST.read_text())


def save_manifest(m: dict) -> None:
    m["entries"] = dict(sorted(m["entries"].items()))
    MANIFEST.write_text(json.dumps(m, indent=2) + "\n")


def style_entries(m: dict) -> dict[str, tuple[str, dict]]:
    """Upstream style name -> (manifest key, entry) for every ported style."""
    out: dict[str, tuple[str, dict]] = {}
    for key, e in m["entries"].items():
        match = re.fullmatch(r"styles/([^/]+)/catppuccin\.user\.less", e.get("path", ""))
        if e.get("repo") == "userstyles" and match:
            out[match.group(1)] = (key, e)
    return out


def template_path(entry: dict) -> Path:
    return THEMES_DIR / "templates" / entry["template"]


# ============================================================
# RENDER + APPLY
# ============================================================


def regenerate() -> list[str]:
    """Re-render Stylus output for every palette; returns themes that failed."""
    themes = sorted(p.stem for p in PALETTES.glob("*.json"))

    def one(theme: str) -> tuple[str, bool]:
        out = subprocess.run(
            [str(GENERATE), theme, "--stylus-only"], capture_output=True, text=True, timeout=600
        )
        return theme, out.returncode == 0

    with concurrent.futures.ThreadPoolExecutor(max_workers=8) as pool:
        failed = [t for t, ok in pool.map(one, themes) if not ok]
    apply_current()
    return failed


def apply_current() -> None:
    """Hand the current theme's styles to the local Stylus server."""
    script = (
        'source "$1/lib/config.sh"; source "$LIB_DIR/utils.sh"; '
        'source "$APPS_DIR/desktop.sh"; apply_stylus "$(cat "$CURRENT_THEME_FILE")"'
    )
    subprocess.run(["bash", "-c", script, "_", str(THEMES_DIR)], check=False)


def remove_outputs(filename: str) -> None:
    """Drop one style's rendered files (exact paths only)."""
    for d in [*GENERATED.glob("*/stylus"), CURRENT / "stylus"]:
        target = d / filename
        if target.is_file():
            target.unlink()


def current_port() -> str:
    for line in (THEMES_DIR / "lib" / "config.sh").read_text().splitlines():
        if line.startswith("STYLUS_PORT="):
            return line.split("=", 1)[1].strip()
    return "8790"


# ============================================================
# COMMANDS
# ============================================================


def report(p: Ported, verb: str) -> None:
    print(f"✓ {p.name:28} {verb}")
    for w in p.warnings:
        print(f"    ▲ {w}")


def cmd_list(ported_only: bool) -> None:
    ensure_clone(pull=False)
    entries = style_entries(load_manifest())
    names = upstream_names()
    rows: list[str] = []
    for n in names:
        if n in entries:
            _, e = entries[n]
            mark = "●" if e.get("auto") else "◆"
            rows.append(f"{mark} {n}")
        elif not ported_only:
            rows.append(f"  {n}")
    width = max((len(r) for r in rows), default=0) + 2
    cols = max(1, shutil.get_terminal_size((100, 24)).columns // width)
    for i in range(0, len(rows), cols):
        print("".join(r.ljust(width) for r in rows[i:i + cols]).rstrip())
    auto = sum(1 for _, e in entries.values() if e.get("auto"))
    print(f"\n● auto-ported ({auto})   ◆ hand-ported ({len(entries) - auto})   "
          f"{len(names)} upstream @ {head_sha()}")


def cmd_check(names: list[str]) -> int:
    ensure_clone(pull=False)
    good, bad = port_many(names)
    for p in good:
        report(p, "converts and compiles")
    for n, err in bad.items():
        print(f"✗ {n:28} {err}")
    print(f"\n{len(good)} ok, {len(bad)} failed")
    return 1 if bad else 0


def cmd_add(names: list[str], replace: bool) -> int:
    ensure_clone(pull=False)
    m = load_manifest()
    entries = style_entries(m)
    todo: list[str] = []
    for n in names:
        hand = n in entries and not entries[n][1].get("auto")
        if hand and not replace:
            print(f"◆ {n:28} hand-ported ({entries[n][1]['template']}); --replace to take it over")
        else:
            todo.append(n)
    good, bad = port_many(todo)
    sha = head_sha()
    for p in good:
        entry: dict
        if p.name in entries:
            key, entry = entries[p.name]
            dest = template_path(entry)
            if not entry.get("auto") and dest.is_file():
                REPLACED.mkdir(parents=True, exist_ok=True)
                backup = REPLACED / f"{dest.name}.{time.strftime('%Y%m%d-%H%M%S')}"
                shutil.copy2(dest, backup)
                print(f"    hand port saved to {backup}")
        else:
            key = f"stylus-{p.name}"
            dest = TEMPLATES / f"{p.name}.user.less.tmpl"
            entry = {"template": f"stylus/{dest.name}", "repo": "userstyles",
                     "path": f"styles/{p.name}/catppuccin.user.less"}
        dest.write_text(p.text)
        entry.update({"synced": sha, "auto": True})
        entry.pop("note", None)
        m["entries"][key] = entry
        report(p, f"-> templates/{entry['template']}")
    for n, err in bad.items():
        print(f"✗ {n:28} {err}")
    if good:
        save_manifest(m)
        finish_render()
        port = current_port()
        print(f"\nInstall in Stylus from http://127.0.0.1:{port}/ (one click per style).")
    return 1 if bad else 0


def cmd_rm(names: list[str]) -> int:
    m = load_manifest()
    entries = style_entries(m)
    status = 0
    for n in names:
        if n not in entries or not entries[n][1].get("auto"):
            print(f"✗ {n:28} not an auto-ported style")
            status = 1
            continue
        key, entry = entries[n]
        tmpl = template_path(entry)
        if tmpl.is_file():
            tmpl.unlink()
        remove_outputs(tmpl.name.removesuffix(".tmpl"))
        del m["entries"][key]
        print(f"✓ {n:28} removed (uninstall it in Stylus too)")
    save_manifest(m)
    return status


def cmd_sync(notify: bool) -> int:
    ensure_clone(pull=True)
    m = load_manifest()
    auto = {n: ke for n, ke in style_entries(m).items() if ke[1].get("auto")}
    gone = [n for n in auto if not source_path(n).is_file()]
    good, bad = port_many([n for n in auto if n not in gone])
    sha = head_sha()
    changed: list[str] = []
    for p in good:
        _, entry = auto[p.name]
        dest = template_path(entry)
        if not dest.is_file() or dest.read_text() != p.text:
            dest.write_text(p.text)
            changed.append(p.name)
            report(p, "updated")
        entry["synced"] = sha
    for n, err in bad.items():
        print(f"✗ {n:28} kept the previous port: {err}")
    for n in gone:
        print(f"▲ {n:28} no longer upstream; kept as-is")
    save_manifest(m)
    if changed:
        finish_render()
    print(f"{len(auto)} auto-ported style(s) @ {sha}: "
          f"{len(changed)} updated, {len(bad)} failed, {len(gone)} gone upstream")
    if notify and (changed or bad or gone):
        lines = []
        if changed:
            lines.append("Updated: " + ", ".join(changed))
        if bad:
            lines.append("Failed: " + ", ".join(bad))
        if gone:
            lines.append("Gone upstream: " + ", ".join(gone))
        subprocess.run(
            ["notify-send", "-a", "theme", "Stylus userstyles synced", "\n".join(lines)],
            check=False,
        )
    return 1 if bad else 0


def finish_render() -> None:
    failed = regenerate()
    if failed:
        print("✗ stylus render failed for: " + " ".join(failed))


def main() -> None:
    ap = argparse.ArgumentParser(description=(__doc__ or "").split("\n", 1)[0])
    sub = ap.add_subparsers(dest="cmd", required=True)
    s = sub.add_parser("list", help="upstream styles and port status")
    s.add_argument("--ported", action="store_true", help="only ported styles")
    for cmd, text in (("add", "port styles"), ("check", "dry run")):
        s = sub.add_parser(cmd, help=text)
        s.add_argument("names", nargs="*", metavar="NAME")
        s.add_argument("--all", action="store_true", help="every upstream style")
        if cmd == "add":
            s.add_argument("--replace", action="store_true",
                           help="take over hand-ported templates (old one is backed up)")
    s = sub.add_parser("rm", help="drop auto-ported styles")
    s.add_argument("names", nargs="+", metavar="NAME")
    s = sub.add_parser("sync", help="pull upstream and re-port changes")
    s.add_argument("--notify", action="store_true", help="desktop notification on changes")
    a = ap.parse_args()

    try:
        if a.cmd == "list":
            cmd_list(a.ported)
        elif a.cmd in ("add", "check"):
            ensure_clone(pull=False)
            names = upstream_names() if a.all else a.names
            if not names:
                sys.exit(f"{a.cmd}: give style names or --all (see `list`)")
            sys.exit(cmd_add(names, a.replace) if a.cmd == "add" else cmd_check(names))
        elif a.cmd == "rm":
            sys.exit(cmd_rm(a.names))
        elif a.cmd == "sync":
            sys.exit(cmd_sync(a.notify))
    except PortError as e:
        sys.exit(f"stylus-port: {e}")


if __name__ == "__main__":
    main()
